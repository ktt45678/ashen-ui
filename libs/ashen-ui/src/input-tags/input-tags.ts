import {
  ChangeDetectionStrategy,
  Component,
  ElementRef,
  OnInit,
  booleanAttribute,
  computed,
  forwardRef,
  inject,
  input,
  model,
  signal,
  viewChild,
} from '@angular/core';
import { ControlValueAccessor, NG_VALUE_ACCESSOR } from '@angular/forms';
import {
  type SnClass,
  type SnAttrs,
  type SnPartSource,
  type SnStyle,
  resolveSnClass,
  resolveSnStyle,
  resolveSnAttrs,
  SN_PART_SOURCE,
  SnPart,
  SnInputTagsIntl,
  SN_INPUT_DEFAULTS,
  snDefault,
  snControlAttrs,
} from 'ashen-ui/core';
import { snControlStatus } from 'ashen-ui/cdk';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';
import { Chip } from 'ashen-ui/chip';

export type InputTagsSize = 'sm' | 'md' | 'lg';

const INPUT_TAGS_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  root: [],
  shell: [],
  input: ['id', 'value', 'placeholder', 'disabled', 'aria-describedby', 'aria-invalid'],
};

@Component({
  selector: 'sn-input-tags',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Chip, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './input-tags.html',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => InputTags),
      multi: true,
    },
    { provide: SN_PART_SOURCE, useExisting: forwardRef(() => InputTags) },
  ],
  host: {
    class: 'sn-input-tags',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
  },
})
export class InputTags implements ControlValueAccessor, OnInit, SnPartSource {
  readonly value = model<string[]>([]);
  readonly placeholder = input<string | undefined>(undefined);
  readonly invalid = input(false, { transform: booleanAttribute });
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly size = input<InputTagsSize>(snDefault(SN_INPUT_DEFAULTS, 'size', 'md'));
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();

  readonly reservedAttrs = (section: string): readonly string[] =>
    INPUT_TAGS_RESERVED_ATTRS[section] ?? [];

  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });
  private readonly intl = inject(SnInputTagsIntl);

  protected readonly text = signal('');
  private readonly disabledFromForms = signal(false);

  protected readonly inputRef = viewChild<ElementRef<HTMLInputElement>>('inputEl');

  protected readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  private readonly status = snControlStatus({
    invalid: this.invalid,
    onValueChange: (value) => {
      const tags: string[] = (value as string[] | null) ?? [];
      this.fieldContext?.setFilled(tags.length > 0);
    },
  });

  protected readonly effectiveInvalid = this.status.invalid;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.addTag,
  );

  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
  });

  protected readonly controlId = this.attrs.controlId;

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly snClassResolved = computed(() =>
    resolveSnClass(this.snClass(), 'root', true),
  );

  protected readonly chipClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'chip', false),
  );

  protected readonly inputClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'input', false),
  );

  protected readonly shellClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'shell', false),
  );

  protected readonly chipStyleExtra = computed(() =>
    resolveSnStyle(this.snStyle(), 'chip', false),
  );

  protected readonly chipAttrsExtra = computed(() =>
    resolveSnAttrs(this.snAttrs(), 'chip', false),
  );

  private onChange: (value: string[]) => void = () => {};
  private onTouched: () => void = () => {};

  ngOnInit(): void {
    this.fieldContext?.setFilled(this.value().length > 0 || this.text() !== '');
    this.status.connect();
  }

  protected addTag(raw: string): void {
    if (this.isDisabled()) return;
    const trimmed = raw.trim();
    if (!trimmed) return;
    const current = this.value();
    if (current.includes(trimmed)) {
      this.text.set('');
      return;
    }
    const next = [...current, trimmed];
    this.value.set(next);
    this.onChange(next);
    this.text.set('');
    this.fieldContext?.setFilled(true);
  }

  protected removeTag(tag: string): void {
    if (this.isDisabled()) return;
    const next = this.value().filter((t) => t !== tag);
    this.value.set(next);
    this.onChange(next);
    this.fieldContext?.setFilled(next.length > 0 || this.text() !== '');
  }

  protected onInput(event: Event): void {
    this.text.set((event.target as HTMLInputElement).value);
    this.fieldContext?.setFilled(this.value().length > 0 || this.text() !== '');
  }

  protected onKeydown(event: KeyboardEvent): void {
    // Enter while an IME is composing confirms the composition, not the tag.
    if (event.isComposing || event.keyCode === 229) return;
    if (event.key === 'Enter' || event.key === ',') {
      event.preventDefault();
      this.addTag(this.text());
    } else if (event.key === 'Backspace' && this.text() === '') {
      const current = this.value();
      if (current.length > 0) {
        this.removeTag(current[current.length - 1]);
      }
    }
  }

  protected commitPending(): void {
    this.addTag(this.text());
    this.fieldContext?.registerFocus(false);
    this.onTouched();
    this.status.markTouched();
  }

  protected focusInput(): void {
    this.inputRef()?.nativeElement.focus();
  }

  protected onFocus(): void {
    this.fieldContext?.registerFocus(true);
  }

  writeValue(value: string[]): void {
    this.value.set(value ?? []);
    this.fieldContext?.setFilled((value ?? []).length > 0);
    this.status.sync();
  }

  registerOnChange(fn: (value: string[]) => void): void {
    this.onChange = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouched = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
