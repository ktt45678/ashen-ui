import {
  ChangeDetectionStrategy,
  Component,
  ElementRef,
  OnDestroy,
  OnInit,
  TemplateRef,
  ViewContainerRef,
  booleanAttribute,
  computed,
  effect,
  forwardRef,
  inject,
  input,
  model,
  output,
  signal,
  viewChild,
} from '@angular/core';
import { ControlValueAccessor, NG_VALUE_ACCESSOR } from '@angular/forms';
import { DOWN_ARROW, ENTER, ESCAPE, SPACE, TAB, UP_ARROW } from '@angular/cdk/keycodes';
import { Subscription } from 'rxjs';
import {
  SN_PART_SOURCE,
  SnIconRegistry,
  SnPart,
  resolveSnClass,
  snAnimated,
  type SnAttrs,
  type SnClass,
  type SnPartSource,
  SnSelectIntl,
  snNextId,
  type SnShowHideAnimation,
  type SnStyle,
  snControlAttrs,
} from 'ashen-ui/core';
import { snOverlayPanel, snOverlaySelect, snSelectionModel } from 'ashen-ui/cdk';
import { Icon } from 'ashen-ui/icon';
import { Tree, type TreeNode } from 'ashen-ui/tree';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';

function findNode(nodes: readonly TreeNode[], key: string | null): TreeNode | null {
  if (key === null) return null;
  for (const n of nodes) {
    if (n.key === key) return n;
    if (n.children) {
      const found = findNode(n.children, key);
      if (found) return found;
    }
  }
  return null;
}

const TREE_SELECT_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  trigger: [
    'type',
    'role',
    'aria-expanded',
    'aria-haspopup',
    'aria-controls',
    'aria-label',
    'aria-describedby',
    'id',
    'disabled',
  ],
  panel: ['id', 'aria-label'],
};

@Component({
  selector: 'sn-tree-select',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Icon, Tree, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './tree-select.html',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => TreeSelect),
      multi: true,
    },
    {
      provide: SN_PART_SOURCE,
      useExisting: forwardRef(() => TreeSelect),
    },
  ],
  host: {
    class: 'sn-tree-select',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
    '[attr.data-sn-open]': 'isOpen() ? "" : null',
    '[attr.data-sn-disabled]': 'isDisabled() ? "" : null',
  },
})
export class TreeSelect implements ControlValueAccessor, OnInit, OnDestroy, SnPartSource {
  protected readonly icons = inject(SnIconRegistry);

  readonly value = model<string | null>(null);
  readonly nodes = input<readonly TreeNode[]>([]);
  readonly placeholder = input<string | undefined>(undefined);
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly ariaLabel = input<string | undefined>(undefined);
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();
  readonly animated = input(true, { transform: booleanAttribute });
  /**
   * `animated` AND-ed with the app-wide motion setting. Read this, never
   * `animated()` directly, or SN_ANIMATIONS_DISABLED and prefers-reduced-motion
   * cannot skip the exit animation.
   */
  readonly _animated = snAnimated(this.animated);
  readonly animation = input<SnShowHideAnimation | undefined>(undefined);
  readonly expandedKeys = model<readonly string[]>([]);

  readonly nodeSelect = output<{ key: string; node: TreeNode }>();

  protected readonly panelTpl = viewChild<TemplateRef<unknown>>('panelTpl');
  protected readonly triggerBtn = viewChild<ElementRef<HTMLButtonElement>>('triggerBtn');

  private readonly vcr = inject(ViewContainerRef);
  private readonly intl = inject(SnSelectIntl);
  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });

  private readonly disabledFromForms = signal(false);
  readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  readonly panelId = snNextId('sn-tree-select-panel');
  private readonly _triggerId = snNextId('sn-tree-select-trigger');
  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
    fallbackId: this._triggerId,
  });

  protected readonly triggerId = this.attrs.controlId;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.placeholder,
  );

  private readonly selectedKeys = signal<string[]>([]);
  private readonly selection = snSelectionModel<string>(() => ({
    multiple: false,
    trackBy: (key) => key,
    unique: true,
    value: this.selectedKeys,
  }));
  protected readonly selectedKey = computed(() => this.selection.selected()[0] ?? null);
  protected readonly selectedNode = computed(() => findNode(this.nodes(), this.selectedKey()));
  private readonly selectionSync = effect(() => {
    const value = this.value();
    this.selection.set(value === null ? [] : [value]);
  });

  protected readonly snClassResolved = computed(() => resolveSnClass(this.snClass(), 'root', true));

  protected readonly triggerClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'trigger', false),
  );

  protected readonly valueClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'value', false),
  );

  protected readonly arrowClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'arrow', false),
  );

  protected readonly panelClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'panel', false),
  );

  readonly reservedAttrs = (section: string): readonly string[] =>
    TREE_SELECT_RESERVED_ATTRS[section] ?? [];

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly isOpen = signal(false);
  protected readonly isClosing = signal(false);

  protected readonly panelAnimation = computed(() => {
    if (!this._animated()) return 'none';
    const custom = this.animation();
    return (this.isClosing() ? custom?.exit : custom?.enter) ?? null;
  });

  private onChangeFn: (value: string | null) => void = () => {};
  private onTouchedFn: () => void = () => {};

  private subs = new Subscription();
  private readonly panel = snOverlayPanel(() =>
    snOverlaySelect({
      origin: this.triggerBtn()?.nativeElement,
      template: this.panelTpl(),
      viewContainerRef: this.vcr,
      panelClass: 'sn-tree-select-overlay-panel',
      backdropClass: 'sn-select-backdrop',
      closeOnEscape: false,
      closeOnBackdrop: false,
      restoreFocus: false,
      animated: this._animated(),
      animation: this.animation(),
    }),
  );

  ngOnInit(): void {
    const currentVal = this.value();
    this.fieldContext?.setFilled(
      currentVal !== null && currentVal !== undefined && currentVal !== '',
    );
  }

  ngOnDestroy(): void {
    this.subs.unsubscribe();
    this.panel.dispose();
  }

  protected onTriggerClick(): void {
    if (this.isDisabled()) return;
    if (this.isOpen()) {
      this.requestClose();
    } else {
      this.openPanel();
    }
  }

  protected onTriggerKeydown(event: KeyboardEvent): void {
    if (this.isDisabled()) return;
    const key = event.keyCode;

    if (!this.isOpen()) {
      if (key === ENTER || key === SPACE || key === DOWN_ARROW || key === UP_ARROW) {
        event.preventDefault();
        this.openPanel();
      }
      return;
    }

    if (key === ESCAPE) {
      event.preventDefault();
      this.requestClose();
    } else if (key === TAB) {
      this.detach();
    }
  }

  protected onTreeSelect(event: { key: string; node: TreeNode }): void {
    const { key, node } = event;
    if (node.children && node.children.length > 0) {
      const current = this.expandedKeys();
      const idx = current.indexOf(key);
      if (idx === -1) {
        this.expandedKeys.set([...current, key]);
      } else {
        this.expandedKeys.set(current.filter((k) => k !== key));
      }
      return;
    }
    this.selection.select(key);
    const value = this.selectedKey();
    this.value.set(value);
    this.onChangeFn(value);
    this.onTouchedFn();
    this.fieldContext?.setFilled(true);
    this.nodeSelect.emit({ key, node });
    this.requestClose();
    this.restoreFocus();
  }

  private openPanel(): void {
    if (this.isOpen() && !this.isClosing()) return;
    if (this.panel.isClosing()) this.panel.detach();
    if (!this.panel.open()) return;

    this.isOpen.set(true);
    this.isClosing.set(false);
    this.fieldContext?.registerFocus(true);
    this.bindOverlayEvents();

    setTimeout(() => {
      const panelEl = document.getElementById(this.panelId);
      if (panelEl) {
        const treeItem = panelEl.querySelector<HTMLElement>('[tabindex="0"]');
        treeItem?.focus();
      }
    }, 0);
  }

  private bindOverlayEvents(): void {
    this.subs.add(this.panel.backdropClick.subscribe(() => this.requestClose()));
    this.subs.add(
      this.panel.keydown.subscribe((event: KeyboardEvent) => {
        const key = event.keyCode;
        if (key === ESCAPE) {
          event.preventDefault();
          this.requestClose();
          this.restoreFocus();
        } else if (key === TAB) {
          this.detach();
        }
      }),
    );
    this.subs.add(this.panel.afterClosed.subscribe(() => this.finalizeDetach()));
  }

  protected requestClose(): void {
    if (!this.isOpen() || this.isClosing()) return;
    this.isClosing.set(true);
    this.panel.close();
  }

  private detach(): void {
    this.panel.detach();
  }

  private finalizeDetach(): void {
    this.subs.unsubscribe();
    this.subs = new Subscription();
    this.isOpen.set(false);
    this.isClosing.set(false);
    this.onTouchedFn();
    this.fieldContext?.registerFocus(false);
  }

  private restoreFocus(): void {
    this.triggerBtn()?.nativeElement.focus();
  }

  writeValue(value: string | null): void {
    const next = value ?? null;
    this.selection.set(next === null ? [] : [next]);
    this.value.set(next);
    this.fieldContext?.setFilled(next !== null && next !== '');
  }

  registerOnChange(fn: (value: string | null) => void): void {
    this.onChangeFn = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouchedFn = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
