import {
  ChangeDetectionStrategy,
  Component,
  ElementRef,
  Injector,
  OnDestroy,
  TemplateRef,
  ViewContainerRef,
  booleanAttribute,
  computed,
  contentChildren,
  forwardRef,
  inject,
  input,
  model,
  runInInjectionContext,
  signal,
  viewChild,
} from '@angular/core';
import { NgTemplateOutlet } from '@angular/common';
import { ControlValueAccessor } from '@angular/forms';
import { DOWN_ARROW, END, ENTER, ESCAPE, HOME, SPACE, TAB, UP_ARROW } from '@angular/cdk/keycodes';
import { Subscription } from 'rxjs';
import {
  SN_PART_SOURCE,
  IconTemplate,
  SnIconRegistry,
  SnPart,
  type SnAttrs,
  type SnClass,
  type SnPartSource,
  type SnShowHideAnimation,
  type SnStyle,
  SnSelectIntl,
  resolveSnClass,
  snAnimated,
  snNextId,
  snControlAttrs,
} from 'ashen-ui/core';
import {
  provideSnValueAccessor,
  snFormControl,
  snListNavigator,
  snOverlayPanel,
  snOverlaySelect,
  type SnListNavigatorRef,
} from 'ashen-ui/cdk';
import { Icon } from 'ashen-ui/icon';
import { ListOption, SN_LISTBOX } from 'ashen-ui/listbox';

const SELECT_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  trigger: [
    'role',
    'aria-expanded',
    'aria-haspopup',
    'aria-controls',
    'aria-activedescendant',
    'aria-label',
    'disabled',
  ],
  clear: ['type', 'aria-label'],
  panel: ['role', 'id', 'aria-label'],
};

@Component({
  selector: 'sn-select',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Icon, NgTemplateOutlet, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './select.html',
  styleUrl: './select.scss',
  providers: [
    provideSnValueAccessor(Select),
    {
      provide: SN_LISTBOX,
      useFactory: (self: Select) => self.context,
      deps: [Select],
    },
    {
      provide: SN_PART_SOURCE,
      useExisting: forwardRef(() => Select),
    },
  ],
  host: {
    class: 'sn-select',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
    '[attr.data-sn-open]': 'isOpen() ? "" : null',
    '[attr.data-sn-disabled]': 'isDisabled() ? "" : null',
  },
})
export class Select implements ControlValueAccessor, OnDestroy, SnPartSource {
  protected readonly icons = inject(SnIconRegistry);

  readonly value = model<unknown>(null);
  /** Mark the selected option with a trailing check icon. */
  readonly checkmark = input(false, { transform: booleanAttribute });
  readonly placeholder = input<string | undefined>(undefined);
  readonly clearable = input(false, { transform: booleanAttribute });
  readonly clearLabel = input<string | undefined>(undefined);
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly ariaLabel = input<string | undefined>(undefined);
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();
  readonly animated = input(true, { transform: booleanAttribute });
  /**
   * `animated` AND-ed with the app-wide motion setting. Read this, never
   * `animated()` directly, or SN_ANIMATIONS_DISABLED and prefers-reduced-motion
   * cannot skip the exit animation.
   */
  readonly _animated = snAnimated(this.animated);
  readonly animation = input<SnShowHideAnimation | undefined>(undefined);
  /**
   * `'trigger'` keeps the panel as wide as the trigger. `'auto'` uses the trigger
   * width as the minimum, so a panel class can make it wider (a multi-column list).
   */
  readonly panelWidth = input<'trigger' | 'auto'>('trigger');

  protected readonly options = contentChildren(ListOption);
  protected readonly iconTemplates = contentChildren(IconTemplate);
  protected readonly panelTpl = viewChild<TemplateRef<unknown>>('panelTpl');
  protected readonly triggerBtn = viewChild<ElementRef<HTMLButtonElement>>('triggerBtn');

  private readonly injector = inject(Injector);
  private readonly intl = inject(SnSelectIntl);
  private readonly vcr = inject(ViewContainerRef);
  private readonly control = snFormControl<unknown>({
    value: this.value,
    disabled: this.disabled,
  });
  protected readonly fieldContext = this.control.field;
  readonly isDisabled = this.control.isDisabled;

  readonly panelId = snNextId('sn-select-panel');
  private readonly _triggerId = snNextId('sn-select-trigger');
  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
    fallbackId: this._triggerId,
  });

  protected readonly triggerId = this.attrs.controlId;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.placeholder,
  );

  protected readonly effectiveClearLabel = computed(
    () => this.clearLabel() ?? this.intl.clear,
  );

  protected readonly showClear = computed(
    () => this.clearable() && !this.isDisabled() && this.value() !== null && this.value() !== undefined,
  );

  protected readonly arrowIconTpl = computed(
    () => this.iconTemplates().find((template) => template.snIcon() === 'arrow') ?? null,
  );

  protected readonly clearIconTpl = computed(
    () => this.iconTemplates().find((template) => template.snIcon() === 'clear') ?? null,
  );

  protected readonly selectedOption = computed(() => {
    const val = this.value();
    return this.options().find((o) => o.value() === val) ?? null;
  });

  protected readonly displayLabel = computed(() => this.selectedOption()?.getLabel() ?? null);

  protected readonly snClassResolved = computed(() => resolveSnClass(this.snClass(), 'root', true));

  protected readonly triggerClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'trigger', false),
  );

  protected readonly valueClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'value', false),
  );

  protected readonly arrowClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'arrow', false),
  );

  protected readonly clearClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'clear', false),
  );

  protected readonly panelClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'panel', false),
  );

  readonly reservedAttrs = (section: string): readonly string[] =>
    SELECT_RESERVED_ATTRS[section] ?? [];

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly isOpen = signal(false);
  protected readonly isClosing = signal(false);

  protected readonly panelAnimation = computed(() => {
    if (!this._animated()) return 'none';
    const custom = this.animation();
    return (this.isClosing() ? custom?.exit : custom?.enter) ?? null;
  });
  protected readonly activeOptionId = signal<string | null>(null);

  readonly context = {
    value: this.value,
    multiple: signal(false) as ReturnType<typeof signal<boolean>>,
    checkmark: this.checkmark,
    isDisabled: this.isDisabled,
    toggle: (val: unknown): void => {
      if (this.isDisabled()) return;
      this.control.commit(val);
      this.requestClose();
    },
    getTabIndex: (_option: unknown): number => -1,
    onTouched: (): void => this.control.markTouched(),
  };

  private navigator: SnListNavigatorRef<ListOption> | null = null;
  private subs = new Subscription();
  private readonly panel = snOverlayPanel(() =>
    snOverlaySelect({
      origin: this.triggerBtn()?.nativeElement,
      template: this.panelTpl(),
      viewContainerRef: this.vcr,
      panelClass: 'sn-select-overlay-panel',
      matchOriginWidth: this.panelWidth() === 'auto' ? 'min' : true,
      backdropClass: 'sn-select-backdrop',
      closeOnEscape: false,
      closeOnBackdrop: false,
      restoreFocus: false,
      animated: this._animated(),
      animation: this.animation(),
    }),
  );

  ngOnDestroy(): void {
    this.navigator?.destroy();
    this.subs.unsubscribe();
    this.panel.dispose();
  }

  protected onTriggerClick(): void {
    if (this.isDisabled()) return;
    if (this.isOpen()) {
      this.requestClose();
    } else {
      this.openPanel();
    }
  }

  protected onClearPointerDown(event: PointerEvent): void {
    event.preventDefault();
    event.stopPropagation();
  }

  protected clearSelection(event: MouseEvent): void {
    event.preventDefault();
    event.stopPropagation();
    if (!this.showClear()) return;
    this.control.commit(null);
    if (this.isOpen()) {
      this.navigator?.setFirstItemActive();
      this.syncActiveOption();
    }
    this.restoreFocus();
  }

  protected onTriggerKeydown(event: KeyboardEvent): void {
    if (this.isDisabled()) return;
    const key = event.keyCode;

    if (this.isOpen()) {
      this.onOpenKeydown(event);
      return;
    }

    if (
      key === ENTER ||
      key === SPACE ||
      key === DOWN_ARROW ||
      key === UP_ARROW ||
      key === HOME ||
      key === END
    ) {
      event.preventDefault();
      this.openPanel();
      if (key === HOME) {
        setTimeout(() => {
          this.navigator?.setFirstItemActive();
          this.syncActiveOption();
        }, 0);
      } else if (key === END) {
        setTimeout(() => {
          this.navigator?.setLastItemActive();
          this.syncActiveOption();
        }, 0);
      }
    }
  }

  private openPanel(): void {
    if (this.isOpen() && !this.isClosing()) return;
    if (this.panel.isClosing()) this.panel.detach();
    if (!this.panel.open()) return;

    this.isOpen.set(true);
    this.isClosing.set(false);
    this.fieldContext?.registerFocus(true);
    this.bindOverlayEvents();

    setTimeout(() => {
      this.initNavigator();
    }, 0);
  }

  private initNavigator(): void {
    if (!this.panel.isOpen()) return;

    this.navigator?.destroy();
    this.navigator = runInInjectionContext(this.injector, () =>
      snListNavigator({
        items: this.options,
        orientation: 'vertical',
        homeAndEnd: true,
        typeahead: true,
        skipPredicate: (option) => option.isDisabled(),
        activeDescendant: true,
      }),
    );

    const currentVal = this.value();
    const opts = this.options();
    const selectedIdx = opts.findIndex((o) => o.value() === currentVal);
    if (selectedIdx >= 0) {
      this.navigator.setActiveItem(selectedIdx);
    } else {
      this.navigator.setFirstItemActive();
    }

    this.syncActiveOption();
  }

  private scrollActiveIntoView(): void {
    const active = this.navigator?.activeItem();
    if (active && typeof active._el.nativeElement.scrollIntoView === 'function') {
      active._el.nativeElement.scrollIntoView({ block: 'nearest' });
    }
  }

  /**
   * Keys while the panel is open. The trigger's own handler and CDK's overlay
   * keyboard dispatcher both see a keydown on the trigger, so the dispatcher
   * path skips those to apply each key once.
   */
  private onOpenKeydown(event: KeyboardEvent): void {
    const key = event.keyCode;
    if (key === ESCAPE) {
      event.preventDefault();
      this.requestClose();
      return;
    }
    if (key === TAB) {
      this.detach();
      return;
    }
    if (key === ENTER || key === SPACE) {
      event.preventDefault();
      const active = this.navigator?.activeItem();
      if (active && !active.isDisabled()) {
        this.context.toggle(active.value());
      }
      return;
    }
    this.navigate(event);
  }

  private bindOverlayEvents(): void {
    this.subs.add(this.panel.backdropClick.subscribe(() => this.requestClose()));
    this.subs.add(
      this.panel.keydown.subscribe((event: KeyboardEvent) => {
        if (this.triggerBtn()?.nativeElement.contains(event.target as Node)) return;
        this.onOpenKeydown(event);
      }),
    );
    this.subs.add(this.panel.afterClosed.subscribe(() => this.finalizeDetach()));
  }

  protected requestClose(): void {
    if (!this.isOpen() || this.isClosing()) return;
    this.isClosing.set(true);
    this.panel.close();
  }

  private detach(): void {
    this.panel.detach();
  }

  private finalizeDetach(): void {
    this.navigator?.destroy();
    this.navigator = null;
    this.subs.unsubscribe();
    this.subs = new Subscription();
    this.isOpen.set(false);
    this.isClosing.set(false);
    this.activeOptionId.set(null);
    this.control.markTouched();
    this.fieldContext?.registerFocus(false);
    this.restoreFocus();
  }

  private restoreFocus(): void {
    this.triggerBtn()?.nativeElement.focus();
  }

  private navigate(event: KeyboardEvent): void {
    if (this.navigator?.onKeydown(event)) {
      event.preventDefault();
      this.syncActiveOption();
    }
  }

  private syncActiveOption(): void {
    this.activeOptionId.set(this.navigator?.activeItem()?.id() ?? null);
    this.scrollActiveIntoView();
  }

  writeValue(value: unknown): void {
    this.control.writeValue(value);
  }

  registerOnChange(fn: (value: unknown) => void): void {
    this.control.registerOnChange(fn);
  }

  registerOnTouched(fn: () => void): void {
    this.control.registerOnTouched(fn);
  }

  setDisabledState(disabled: boolean): void {
    this.control.setDisabledState(disabled);
  }
}
