import {
  ChangeDetectionStrategy,
  Component,
  DestroyRef,
  Injector,
  OnInit,
  booleanAttribute,
  computed,
  forwardRef,
  inject,
  input,
  model,
  numberAttribute,
  signal,
} from '@angular/core';
import { ControlValueAccessor, NgControl, NG_VALUE_ACCESSOR } from '@angular/forms';
import { takeUntilDestroyed } from '@angular/core/rxjs-interop';
import {
  SN_PART_SOURCE,
  SnPart,
  type SnAttrs,
  type SnClass,
  type SnPartSource,
  type SnStyle,
  resolveSnClass,
  snControlAttrs,
} from 'ashen-ui/core';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';

const SLIDER_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  input: [
    'type',
    'id',
    'min',
    'max',
    'step',
    'value',
    'disabled',
    'aria-describedby',
    'aria-orientation',
    'aria-valuetext',
  ],
};

export type SliderOrientation = 'horizontal' | 'vertical';

@Component({
  selector: 'sn-slider',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [SnPart],
  hostDirectives: [SnPart],
  templateUrl: './slider.html',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => Slider),
      multi: true,
    },
    { provide: SN_PART_SOURCE, useExisting: forwardRef(() => Slider) },
  ],
  host: {
    class: 'sn-slider-wrapper',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
    '[class.sn-slider-disabled]': 'isDisabled()',
    '[class.sn-slider-vertical]': 'isVertical()',
    '[attr.data-sn-disabled]': 'isDisabled() ? "" : null',
    '[attr.data-sn-orientation]': 'orientation()',
  },
})
export class Slider implements ControlValueAccessor, OnInit, SnPartSource {
  readonly value = model<number>(0);
  /**
   * Which way the track runs. A vertical slider fills from the bottom, and its
   * length comes from `--sn-slider-length` rather than from the container.
   */
  readonly orientation = input<SliderOrientation>('horizontal');
  readonly min = input(0, { transform: numberAttribute });
  readonly max = input(100, { transform: numberAttribute });
  readonly step = input(1, { transform: numberAttribute });
  /**
   * How far the loaded range extends, in the slider's own units. Drawn as a
   * second bar behind the fill, like a video player's buffered segment.
   */
  readonly buffered = input<number | null | undefined>(null);
  readonly showValue = input(true, { transform: booleanAttribute });
  readonly formatValue = input<((v: number) => string) | undefined>(undefined);
  readonly disabled = input(false, { transform: booleanAttribute });
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();

  readonly reservedAttrs = (section: string): readonly string[] =>
    SLIDER_RESERVED_ATTRS[section] ?? [];

  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });
  private readonly injector = inject(Injector);
  private readonly destroyRef = inject(DestroyRef);

  private ngControl: NgControl | null = null;
  private readonly disabledFromForms = signal(false);

  protected readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  protected readonly pct = computed(() => {
    const mn = this.min();
    const mx = this.max();
    if (mx === mn) return 0;
    return ((this.value() - mn) / (mx - mn)) * 100;
  });

  protected readonly bufferPct = computed(() => {
    const buffered = this.buffered();
    const mn = this.min();
    const mx = this.max();
    if (buffered == null || mx === mn) return null;
    return Math.min(100, Math.max(0, ((buffered - mn) / (mx - mn)) * 100));
  });

  protected readonly isVertical = computed(() => this.orientation() === 'vertical');

  // The unused half resolves to null, which drops the inline style instead of fighting the stylesheet.
  protected readonly bufferWidth = computed(() => (this.isVertical() ? null : this.bufferPct()));
  protected readonly bufferHeight = computed(() => (this.isVertical() ? this.bufferPct() : null));
  protected readonly fillWidth = computed(() => (this.isVertical() ? null : this.pct()));
  protected readonly fillHeight = computed(() => (this.isVertical() ? this.pct() : null));
  protected readonly thumbInlineStart = computed(() =>
    this.isVertical() ? null : this.pct(),
  );
  protected readonly thumbBottom = computed(() => (this.isVertical() ? this.pct() : null));

  protected readonly displayValue = computed(() => {
    const f = this.formatValue();
    return f ? f(this.value()) : String(this.value());
  });

  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
  });

  protected readonly controlId = this.attrs.controlId;

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly snClassResolved = computed(() =>
    resolveSnClass(this.snClass(), 'root', true),
  );

  protected readonly trackClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'track', false),
  );

  protected readonly bufferClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'buffer', false),
  );

  protected readonly fillClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'fill', false),
  );

  protected readonly thumbClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'thumb', false),
  );

  protected readonly inputClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'input', false),
  );

  protected readonly valueClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'value', false),
  );

  private onChange: (value: number) => void = () => {};
  private onTouched: () => void = () => {};

  ngOnInit(): void {
    this.ngControl = this.injector.get(NgControl, null, { self: true, optional: true });
    this.fieldContext?.setFilled(true);
    const ctrl = this.ngControl?.control;
    if (ctrl) {
      ctrl.statusChanges.pipe(takeUntilDestroyed(this.destroyRef)).subscribe(() => {});
    }
  }

  protected onInput(event: Event): void {
    const n = +(event.target as HTMLInputElement).value;
    this.value.set(n);
    this.onChange(n);
    this.fieldContext?.setFilled(true);
  }

  protected onFocus(): void {
    this.fieldContext?.registerFocus(true);
  }

  protected onBlur(): void {
    this.fieldContext?.registerFocus(false);
    this.onTouched();
  }

  writeValue(v: number): void {
    this.value.set(v ?? 0);
  }

  registerOnChange(fn: (value: number) => void): void {
    this.onChange = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouched = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
