import {
  ChangeDetectionStrategy,
  Component,
  OnInit,
  booleanAttribute,
  computed,
  forwardRef,
  inject,
  input,
  model,
  signal,
} from '@angular/core';
import { ControlValueAccessor, NG_VALUE_ACCESSOR } from '@angular/forms';
import {
  type SnClass,
  type SnAttrs,
  type SnPartSource,
  type SnStyle,
  resolveSnClass,
  SN_PART_SOURCE,
  SnPart,
  SnPasswordIntl,
  SN_INPUT_DEFAULTS,
  snDefault,
  snControlAttrs,
} from 'ashen-ui/core';
import { snControlStatus } from 'ashen-ui/cdk';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';
import { Button } from 'ashen-ui/button';

export type InputPasswordSize = 'sm' | 'md' | 'lg';

const INPUT_PASSWORD_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  root: [],
  input: ['id', 'type', 'value', 'placeholder', 'disabled', 'aria-describedby', 'aria-invalid'],
  meter: [],
  meterBar: [],
  meterLabel: [],
};

@Component({
  selector: 'sn-input-password',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Button, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './input-password.html',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => InputPassword),
      multi: true,
    },
    { provide: SN_PART_SOURCE, useExisting: forwardRef(() => InputPassword) },
  ],
  host: {
    class: 'sn-input-password',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
  },
})
export class InputPassword implements ControlValueAccessor, OnInit, SnPartSource {
  readonly value = model<string>('');
  readonly meter = input(false, { transform: booleanAttribute });
  readonly placeholder = input<string | undefined>(undefined);
  readonly invalid = input(false, { transform: booleanAttribute });
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly size = input<InputPasswordSize>(snDefault(SN_INPUT_DEFAULTS, 'size', 'md'));
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();

  readonly reservedAttrs = (section: string): readonly string[] =>
    INPUT_PASSWORD_RESERVED_ATTRS[section] ?? [];

  readonly showPasswordLabel = input<string | undefined>(undefined);
  readonly hidePasswordLabel = input<string | undefined>(undefined);

  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });
  private readonly intl = inject(SnPasswordIntl);

  protected readonly visible = signal(false);
  private readonly disabledFromForms = signal(false);

  protected readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  private readonly status = snControlStatus({
    invalid: this.invalid,
    onValueChange: (value) => this.fieldContext?.setFilled(value !== ''),
  });

  protected readonly effectiveInvalid = this.status.invalid;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.placeholder,
  );

  protected readonly effectiveShowLabel = computed(
    () => this.showPasswordLabel() ?? this.intl.show,
  );

  protected readonly effectiveHideLabel = computed(
    () => this.hidePasswordLabel() ?? this.intl.hide,
  );

  protected readonly toggleAriaLabel = computed(() =>
    this.visible() ? this.effectiveHideLabel() : this.effectiveShowLabel(),
  );

  protected readonly strengthScore = computed(() => {
    const v = this.value();
    if (!v) return 0;
    let score = 0;
    if (v.length >= 8) score++;
    if (/[a-z]/.test(v) && /[A-Z]/.test(v)) score++;
    if (/\d/.test(v)) score++;
    if (/[^a-zA-Z0-9]/.test(v)) score++;
    return score;
  });

  protected readonly strengthColor = computed(() => {
    const s = this.strengthScore();
    if (s <= 1) return 'var(--sn-color-error)';
    if (s === 2) return 'var(--sn-color-warning)';
    if (s === 3) return 'var(--sn-color-info)';
    return 'var(--sn-color-success)';
  });

  protected readonly strengthLabel = computed(() => {
    const s = this.strengthScore();
    if (s <= 1) return this.intl.strengthWeak;
    if (s === 2) return this.intl.strengthFair;
    if (s === 3) return this.intl.strengthGood;
    return this.intl.strengthStrong;
  });

  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
  });

  protected readonly controlId = this.attrs.controlId;

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly snClassResolved = computed(() =>
    resolveSnClass(this.snClass(), 'root', true),
  );

  protected readonly inputClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'input', false),
  );

  protected readonly toggleClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'toggle', false),
  );

  protected readonly meterClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'meter', false),
  );

  protected readonly meterBarClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'meterBar', false),
  );

  protected readonly meterLabelClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'meterLabel', false),
  );

  private onChange: (value: string) => void = () => {};
  private onTouched: () => void = () => {};

  ngOnInit(): void {
    this.fieldContext?.setFilled(this.value() !== '');
    this.status.connect();
  }

  protected onInputChange(event: Event): void {
    const val = (event.target as HTMLInputElement).value;
    this.value.set(val);
    this.onChange(val);
    this.fieldContext?.setFilled(val !== '');
  }

  protected onFocus(): void {
    this.fieldContext?.registerFocus(true);
  }

  protected onBlur(): void {
    this.fieldContext?.registerFocus(false);
    this.onTouched();
    this.status.markTouched();
  }

  protected toggleVisibility(): void {
    if (this.isDisabled()) return;
    this.visible.update((v) => !v);
  }

  writeValue(value: string): void {
    this.value.set(value ?? '');
    this.fieldContext?.setFilled((value ?? '') !== '');
    this.status.sync();
  }

  registerOnChange(fn: (value: string) => void): void {
    this.onChange = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouched = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
