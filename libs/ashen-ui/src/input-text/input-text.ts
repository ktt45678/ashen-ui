import {
  Directive,
  ElementRef,
  OnInit,
  booleanAttribute,
  computed,
  forwardRef,
  inject,
  input,
} from '@angular/core';
import {
  type SnClass,
  resolveSnClass,
  SN_INPUT_DEFAULTS,
  snControlAttrs,
  snDefault,
} from 'ashen-ui/core';
import { SN_CONTROL_STATUS, SnControlStatusSync, snControlStatus } from 'ashen-ui/cdk';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';

/** `xs` is input-text only, for dense toolbars next to small buttons. */
export type InputTextSize = 'xs' | 'sm' | 'md' | 'lg';

@Directive({
  selector: 'input[snInputText]',
  hostDirectives: [SnControlStatusSync],
  providers: [{ provide: SN_CONTROL_STATUS, useExisting: forwardRef(() => InputText) }],
  host: {
    class: 'sn-input-text',
    '[class.sn-input-text-xs]': 'size() === "xs"',
    '[class.sn-input-text-sm]': 'size() === "sm"',
    '[class.sn-input-text-lg]': 'size() === "lg"',
    '[class.sn-input-text-error]': 'effectiveInvalid()',
    '[attr.id]': 'controlId()',
    '[attr.aria-invalid]': 'effectiveInvalid() ? "true" : null',
    '[attr.aria-required]': 'fieldContext && fieldContext.required() ? "true" : null',
    '[attr.aria-describedby]': 'ariaDescribedBy()',
    '[class]': 'snClassResolved()',
    '[attr.data-sn-size]': 'size()',
    '(focus)': 'onFocus()',
    '(blur)': 'onBlur()',
    '(input)': 'updateFilled()',
  },
})
export class InputText implements OnInit {
  readonly size = input<InputTextSize>(snDefault(SN_INPUT_DEFAULTS, 'size', 'md'));
  readonly invalid = input(false, { transform: booleanAttribute });
  /**
   * The input's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the input, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();

  private readonly el = inject<ElementRef<HTMLInputElement>>(ElementRef);
  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });

  private readonly status = snControlStatus({
    invalid: this.invalid,
    onValueChange: () => this.updateFilled(),
  });

  protected readonly effectiveInvalid = this.status.invalid;

  private readonly attrs = snControlAttrs({ id: this.id, describedBy: this.ariaDescribedby });
  protected readonly controlId = this.attrs.controlId;
  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly snClassResolved = computed(() =>
    resolveSnClass(this.snClass(), 'root', true),
  );

  ngOnInit(): void {
    this.updateFilled();
    this.status.connect();
  }

  /**
   * What "empty" means for this input. Replaced by anything that writes
   * characters into the element the user did not type. See
   * {@link setEmptyPredicate}.
   */
  private isEmpty: () => boolean = () => this.el.nativeElement.value === '';

  /**
   * Redefine emptiness for this input.
   *
   * The floating label, the `filled` state and `data-sn-filled` are all driven
   * by whether the control is empty, and the default answer is "the DOM value
   * is `''`". That is wrong for any input whose element holds characters the
   * user did not type: an input mask writing `(___) ___-____` reads as filled
   * the moment it initialises, so the label floats over an empty field and
   * never comes back down.
   *
   * A mask directive on the same element redefines it:
   *
   * ```ts
   * inject(InputText, { self: true }).setEmptyPredicate(
   *   () => unmask(el.nativeElement.value) === '',
   * );
   * ```
   *
   * This is deliberately mask-library-agnostic: Ashen's own `[snMask]` uses it,
   * and so can Maskito, imask, ngx-mask or anything hand-rolled. Pass `null` to
   * restore the default.
   */
  setEmptyPredicate(fn: (() => boolean) | null): void {
    this.isEmpty = fn ?? (() => this.el.nativeElement.value === '');
    this.updateFilled();
  }

  /**
   * Re-read emptiness and report it to the enclosing field. Call this after
   * changing the element's value from outside Angular's input event, a mask
   * reformatting on blur, say.
   */
  updateFilled(): void {
    this.fieldContext?.setFilled(!this.isEmpty());
  }

  protected onFocus(): void {
    this.fieldContext?.registerFocus(true);
  }

  protected onBlur(): void {
    this.fieldContext?.registerFocus(false);
    this.status.markTouched();
  }

  /** Delegates to `status.sync()`; called by the `SnControlStatusSync` host directive. */
  sync(): void {
    this.status.sync();
  }
}
