function sameDay(a: Date | null, b: Date | null): boolean {
  return (
    a !== null &&
    b !== null &&
    a.getFullYear() === b.getFullYear() &&
    a.getMonth() === b.getMonth() &&
    a.getDate() === b.getDate()
  );
}

function sameMonth(a: Date | null, year: number, month: number): boolean {
  return a !== null && a.getFullYear() === year && a.getMonth() === month;
}

function sameYear(a: Date | null, year: number): boolean {
  return a !== null && a.getFullYear() === year;
}

function addMonths(year: number, month: number, delta: number): { year: number; month: number } {
  const d = new Date(year, month + delta, 1);
  return { year: d.getFullYear(), month: d.getMonth() };
}

function clampDate(d: Date, year: number, month: number): Date {
  const daysInMonth = new Date(year, month + 1, 0).getDate();
  return new Date(year, month, Math.min(d.getDate(), daysInMonth));
}

/**
 * A date as one comparable number, `20260803` for 3 August 2026.
 *
 * Range checks compare days, not instants: a `minDate` of `new Date()` means
 * "from today", and comparing timestamps would rule today out for every hour
 * already past. Deriving the number from the local calendar fields also keeps
 * the comparison clear of time zones and of the hour DST removes.
 */
function dayNumber(d: Date): number {
  return d.getFullYear() * 10000 + d.getMonth() * 100 + d.getDate();
}

const DAYS_PER_WEEK = 7;

// The month and year panes are both a twelve-cell pad, three to a row.
const PAD_COLUMNS = 3;
const PAD_LAST_INDEX = 11;

function clampPadIndex(index: number): number {
  return Math.min(PAD_LAST_INDEX, Math.max(0, index));
}

export type DatePickerMode = 'days' | 'months' | 'years';

