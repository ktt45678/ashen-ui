import {
  ChangeDetectionStrategy,
  Component,
  ElementRef,
  NgZone,
  OnDestroy,
  OnInit,
  TemplateRef,
  ViewContainerRef,
  booleanAttribute,
  computed,
  effect,
  forwardRef,
  inject,
  input,
  model,
  signal,
  viewChild,
} from '@angular/core';
import { NgTemplateOutlet } from '@angular/common';
import { ControlValueAccessor, NG_VALUE_ACCESSOR } from '@angular/forms';
import {
  DOWN_ARROW,
  END,
  ENTER,
  ESCAPE,
  HOME,
  LEFT_ARROW,
  RIGHT_ARROW,
  SPACE,
  TAB,
  UP_ARROW,
} from '@angular/cdk/keycodes';
import { Subscription } from 'rxjs';
import {
  SN_PART_SOURCE,
  SnIconRegistry,
  SnPart,
  resolveSnClass,
  snAnimated,
  type SnAttrs,
  type SnClass,
  type SnPartSource,
  SnSelectIntl,
  snNextId,
  type SnShowHideAnimation,
  type SnStyle,
  snControlAttrs,
} from 'ashen-ui/core';
import { snOverlayPanel, snOverlaySelect, snSelectionModel } from 'ashen-ui/cdk';
import { Icon } from 'ashen-ui/icon';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';

export interface CascadeOption {
  label: string;
  value?: unknown;
  icon?: string;
  children?: CascadeOption[];
}

function findLabel(opts: readonly CascadeOption[], value: unknown): string | null {
  for (const o of opts) {
    if (o.children && o.children.length > 0) {
      const found = findLabel(o.children, value);
      if (found !== null) return found;
    } else if (o.value === value) {
      return o.label;
    }
  }
  return null;
}

function isParent(opt: CascadeOption): boolean {
  return Array.isArray(opt.children) && opt.children.length > 0;
}

const CASCADE_SELECT_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  trigger: [
    'type',
    'role',
    'aria-expanded',
    'aria-haspopup',
    'aria-controls',
    'aria-activedescendant',
    'aria-label',
    'aria-describedby',
    'id',
    'disabled',
  ],
  panel: ['role', 'id', 'aria-label'],
};

@Component({
  selector: 'sn-cascade-select',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Icon, NgTemplateOutlet, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './cascade-select.html',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => CascadeSelect),
      multi: true,
    },
    {
      provide: SN_PART_SOURCE,
      useExisting: forwardRef(() => CascadeSelect),
    },
  ],
  host: {
    class: 'sn-cascade-select',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
    '[attr.data-sn-open]': 'isOpen() ? "" : null',
    '[attr.data-sn-disabled]': 'isDisabled() ? "" : null',
  },
})
export class CascadeSelect implements ControlValueAccessor, OnInit, OnDestroy, SnPartSource {
  protected readonly icons = inject(SnIconRegistry);

  readonly value = model<unknown>(null);
  readonly options = input<readonly CascadeOption[]>([]);
  readonly placeholder = input<string | undefined>(undefined);
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly ariaLabel = input<string | undefined>(undefined);
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();
  readonly animated = input(true, { transform: booleanAttribute });
  /**
   * `animated` AND-ed with the app-wide motion setting. Read this, never
   * `animated()` directly, or SN_ANIMATIONS_DISABLED and prefers-reduced-motion
   * cannot skip the exit animation.
   */
  readonly _animated = snAnimated(this.animated);
  readonly animation = input<SnShowHideAnimation | undefined>(undefined);

  protected readonly panelTpl = viewChild<TemplateRef<unknown>>('panelTpl');
  protected readonly triggerBtn = viewChild<ElementRef<HTMLButtonElement>>('triggerBtn');

  private readonly vcr = inject(ViewContainerRef);
  private readonly intl = inject(SnSelectIntl);
  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });
  private readonly _ngZone = inject(NgZone);

  private readonly disabledFromForms = signal(false);
  readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  readonly panelId = snNextId('sn-cascade-select-panel');
  private readonly _triggerId = snNextId('sn-cascade-select-trigger');
  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
    fallbackId: this._triggerId,
  });

  protected readonly triggerId = this.attrs.controlId;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.placeholder,
  );

  private readonly selectedValues = signal<unknown[]>([]);
  private readonly selection = snSelectionModel<unknown>(() => ({
    multiple: false,
    unique: true,
    value: this.selectedValues,
  }));
  protected readonly selectedValue = computed(() => this.selection.selected()[0] ?? null);
  private readonly selectionSync = effect(() => {
    const value = this.value();
    this.selection.set(value === null || value === undefined ? [] : [value]);
  });

  protected readonly selectedLabel = computed(() =>
    findLabel(this.options(), this.selectedValue()),
  );

  protected readonly snClassResolved = computed(() => resolveSnClass(this.snClass(), 'root', true));

  protected readonly triggerClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'trigger', false),
  );

  protected readonly valueClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'value', false),
  );

  protected readonly arrowClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'arrow', false),
  );

  protected readonly panelClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'panel', false),
  );

  readonly reservedAttrs = (section: string): readonly string[] =>
    CASCADE_SELECT_RESERVED_ATTRS[section] ?? [];

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly activeDescendant = computed(() => {
    const path = this.activePath();
    if (path.length === 0) return null;
    return `${this.panelId}-opt-${path.join('-')}`;
  });

  protected readonly isOpen = signal(false);
  protected readonly isClosing = signal(false);

  protected readonly panelAnimation = computed(() => {
    if (!this._animated()) return 'none';
    const custom = this.animation();
    return (this.isClosing() ? custom?.exit : custom?.enter) ?? null;
  });

  protected readonly openPath = signal<number[]>([]);
  protected readonly activePath = signal<number[]>([]);

  protected readonly isParent = isParent;

  private onChangeFn: (value: unknown) => void = () => {};
  private onTouchedFn: () => void = () => {};

  private subs = new Subscription();
  private readonly panel = snOverlayPanel(() =>
    snOverlaySelect({
      origin: this.triggerBtn()?.nativeElement,
      template: this.panelTpl(),
      viewContainerRef: this.vcr,
      panelClass: 'sn-cascade-select-overlay-panel',
      backdropClass: 'sn-select-backdrop',
      closeOnEscape: false,
      closeOnBackdrop: false,
      restoreFocus: false,
      animated: this._animated(),
      animation: this.animation(),
    }),
  );

  ngOnInit(): void {
    const currentVal = this.value();
    this.fieldContext?.setFilled(currentVal !== null && currentVal !== undefined);
  }

  ngOnDestroy(): void {
    this.subs.unsubscribe();
    this.panel.dispose();
  }

  protected onTriggerClick(): void {
    if (this.isDisabled()) return;
    if (this.isOpen()) {
      this.requestClose();
    } else {
      this.openPanel();
    }
  }

  protected onTriggerKeydown(event: KeyboardEvent): void {
    if (this.isDisabled()) return;
    const key = event.keyCode;

    if (!this.isOpen()) {
      if (key === ENTER || key === SPACE || key === DOWN_ARROW || key === UP_ARROW) {
        event.preventDefault();
        this.openPanel();
        setTimeout(() => {
          const opts = this.options();
          if (opts.length > 0) {
            this.activePath.set([0]);
          }
        }, 0);
      }
      return;
    }

    if (key === ESCAPE) {
      event.preventDefault();
      this.requestClose();
      this.restoreFocus();
    } else if (key === TAB) {
      this.detach();
    } else if (key === DOWN_ARROW) {
      event.preventDefault();
      this.moveActive(1);
    } else if (key === UP_ARROW) {
      event.preventDefault();
      this.moveActive(-1);
    } else if (key === RIGHT_ARROW) {
      event.preventDefault();
      this.activateRight();
    } else if (key === LEFT_ARROW) {
      event.preventDefault();
      this.activateLeft();
    } else if (key === HOME) {
      event.preventDefault();
      this.moveActiveToEnd('first');
    } else if (key === END) {
      event.preventDefault();
      this.moveActiveToEnd('last');
    } else if (key === ENTER || key === SPACE) {
      event.preventDefault();
      this.activateEnter();
    }
  }

  private getCurrentLevelOpts(): CascadeOption[] {
    const path = this.activePath();
    const opts = this.options() as CascadeOption[];
    if (path.length === 0) return [...opts];
    let current = opts;
    for (let i = 0; i < path.length - 1; i++) {
      const parent = current[path[i]];
      if (!parent || !parent.children) return [...opts];
      current = parent.children;
    }
    return [...current];
  }

  private moveActive(delta: number): void {
    const path = this.activePath();
    if (path.length === 0) {
      const opts = this.options();
      if (opts.length > 0) {
        this.activePath.set([delta > 0 ? 0 : opts.length - 1]);
      }
      return;
    }
    const levelOpts = this.getCurrentLevelOpts();
    const currentIdx = path[path.length - 1];
    const newIdx = Math.max(0, Math.min(levelOpts.length - 1, currentIdx + delta));
    this.activePath.set([...path.slice(0, -1), newIdx]);
  }

  private moveActiveToEnd(which: 'first' | 'last'): void {
    const path = this.activePath();
    const levelOpts = this.getCurrentLevelOpts();
    if (levelOpts.length === 0) return;
    const idx = which === 'first' ? 0 : levelOpts.length - 1;
    if (path.length === 0) {
      this.activePath.set([idx]);
    } else {
      this.activePath.set([...path.slice(0, -1), idx]);
    }
  }

  private getActiveOption(): CascadeOption | null {
    const path = this.activePath();
    if (path.length === 0) return null;
    let opts = this.options() as CascadeOption[];
    let opt: CascadeOption | null = null;
    for (const idx of path) {
      if (idx >= opts.length) return null;
      opt = opts[idx];
      if (opt.children) opts = opt.children;
    }
    return opt;
  }

  private activateRight(): void {
    const opt = this.getActiveOption();
    if (!opt) return;
    if (isParent(opt)) {
      const path = this.activePath();
      this.openPath.set([...path]);
      if (opt.children && opt.children.length > 0) {
        this.activePath.set([...path, 0]);
      }
    }
  }

  private activateLeft(): void {
    const path = this.activePath();
    if (path.length <= 1) return;
    const parentPath = path.slice(0, -1);
    this.openPath.set(parentPath.slice(0, -1));
    this.activePath.set(parentPath);
  }

  private activateEnter(): void {
    const opt = this.getActiveOption();
    if (!opt) return;
    if (isParent(opt)) {
      const path = this.activePath();
      const openPath = this.openPath();
      const pathStr = path.join(',');
      const openPathStr = openPath.join(',');
      if (pathStr === openPathStr) {
        this.openPath.set(path.slice(0, -1));
      } else {
        this.openPath.set([...path]);
      }
    } else {
      this.pick(opt);
    }
  }

  protected onOptionMouseenter(path: number[]): void {
    this.activePath.set([...path]);
    const opt = this.getOptionAtPath(path);
    if (opt && isParent(opt)) {
      this.openPath.set([...path]);
    } else {
      this.openPath.set(path.slice(0, -1));
    }
  }

  protected onOptionClick(opt: CascadeOption, path: number[]): void {
    if (isParent(opt)) {
      const openPath = this.openPath();
      const pathStr = path.join(',');
      const openPathStr = openPath.join(',');
      if (pathStr === openPathStr) {
        this.openPath.set(path.slice(0, -1));
      } else {
        this.openPath.set([...path]);
      }
      this.activePath.set([...path]);
    } else {
      this.pick(opt);
    }
  }

  private getOptionAtPath(path: number[]): CascadeOption | null {
    let opts = this.options() as CascadeOption[];
    let opt: CascadeOption | null = null;
    for (const idx of path) {
      if (idx >= opts.length) return null;
      opt = opts[idx];
      if (opt.children) opts = opt.children;
    }
    return opt;
  }

  protected isFlyoutOpen(path: number[]): boolean {
    const openPath = this.openPath();
    if (path.length > openPath.length) return false;
    for (let i = 0; i < path.length; i++) {
      if (openPath[i] !== path[i]) return false;
    }
    return true;
  }

  protected isActive(path: number[]): boolean {
    const activePath = this.activePath();
    if (path.length !== activePath.length) return false;
    for (let i = 0; i < path.length; i++) {
      if (activePath[i] !== path[i]) return false;
    }
    return true;
  }

  protected isSelected(opt: CascadeOption): boolean {
    return !isParent(opt) && opt.value !== undefined && this.selection.isSelected(opt.value);
  }

  protected optionId(path: number[]): string {
    return `${this.panelId}-opt-${path.join('-')}`;
  }

  protected pick(opt: CascadeOption): void {
    this.selection.select(opt.value ?? null);
    const value = this.selectedValue();
    this.value.set(value);
    this.onChangeFn(value);
    this.onTouchedFn();
    this.fieldContext?.setFilled(value !== null && value !== undefined);
    this.openPath.set([]);
    this.activePath.set([]);
    this.requestClose();
    this.restoreFocus();
  }

  private openPanel(): void {
    if (this.isOpen() && !this.isClosing()) return;
    if (this.panel.isClosing()) this.panel.detach();
    if (!this.panel.open()) return;

    this.isOpen.set(true);
    this.isClosing.set(false);
    this.fieldContext?.registerFocus(true);
    this.bindOverlayEvents();
  }

  private bindOverlayEvents(): void {
    this.subs.add(this.panel.backdropClick.subscribe(() => this.requestClose()));
    this.subs.add(
      this.panel.keydown.subscribe((event: KeyboardEvent) => {
        const key = event.keyCode;
        if (key === ESCAPE) {
          event.preventDefault();
          this.requestClose();
          this.restoreFocus();
        } else if (key === TAB) {
          this.detach();
        }
      }),
    );
    this.subs.add(this.panel.afterClosed.subscribe(() => this.finalizeDetach()));
  }

  protected requestClose(): void {
    if (!this.isOpen() || this.isClosing()) return;
    this.isClosing.set(true);
    this.panel.close();
  }

  private detach(): void {
    this.panel.detach();
  }

  private finalizeDetach(): void {
    this.subs.unsubscribe();
    this.subs = new Subscription();
    this.isOpen.set(false);
    this.isClosing.set(false);
    this.openPath.set([]);
    this.activePath.set([]);
    this.onTouchedFn();
    this.fieldContext?.registerFocus(false);
  }

  private restoreFocus(): void {
    this.triggerBtn()?.nativeElement.focus();
  }

  writeValue(value: unknown): void {
    const next = value ?? null;
    this.selection.set(next === null ? [] : [next]);
    this.value.set(next);
    this.fieldContext?.setFilled(next !== null);
  }

  registerOnChange(fn: (value: unknown) => void): void {
    this.onChangeFn = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouchedFn = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
