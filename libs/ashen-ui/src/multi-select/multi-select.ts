import {
  ChangeDetectionStrategy,
  Component,
  ElementRef,
  Injector,
  OnDestroy,
  OnInit,
  TemplateRef,
  ViewContainerRef,
  booleanAttribute,
  computed,
  contentChildren,
  forwardRef,
  inject,
  input,
  model,
  numberAttribute,
  signal,
  viewChild,
} from '@angular/core';
import { ControlValueAccessor, NG_VALUE_ACCESSOR } from '@angular/forms';
import { ActiveDescendantKeyManager } from '@angular/cdk/a11y';
import { DOWN_ARROW, END, ENTER, ESCAPE, HOME, SPACE, TAB, UP_ARROW } from '@angular/cdk/keycodes';
import { Subscription } from 'rxjs';
import {
  SN_PART_SOURCE,
  SnIconRegistry,
  SnPart,
  resolveSnClass,
  resolveSnStyle,
  resolveSnAttrs,
  snAnimated,
  type SnAttrs,
  type SnClass,
  type SnPartSource,
  SnSelectIntl,
  snNextId,
  type SnShowHideAnimation,
  type SnStyle,
  snControlAttrs,
} from 'ashen-ui/core';
import { snOverlayPanel, snOverlaySelect, snSelectionModel } from 'ashen-ui/cdk';
import { Icon } from 'ashen-ui/icon';
import { SN_FORM_FIELD } from 'ashen-ui/form-field';
import { ListOption, SN_LISTBOX } from 'ashen-ui/listbox';
import { Chip } from 'ashen-ui/chip';

const MULTI_SELECT_RESERVED_ATTRS: Readonly<Record<string, readonly string[]>> = {
  trigger: [
    'type',
    'role',
    'aria-expanded',
    'aria-haspopup',
    'aria-controls',
    'aria-activedescendant',
    'aria-label',
    'aria-describedby',
    'id',
    'disabled',
  ],
  panel: ['role', 'aria-multiselectable', 'id', 'aria-label'],
};

@Component({
  selector: 'sn-multi-select',
  changeDetection: ChangeDetectionStrategy.OnPush,
  imports: [Icon, Chip, SnPart],
  hostDirectives: [SnPart],
  templateUrl: './multi-select.html',
  styleUrl: './multi-select.scss',
  providers: [
    {
      provide: NG_VALUE_ACCESSOR,
      useExisting: forwardRef(() => MultiSelect),
      multi: true,
    },
    {
      provide: SN_LISTBOX,
      useFactory: (self: MultiSelect) => self.context,
      deps: [MultiSelect],
    },
    {
      provide: SN_PART_SOURCE,
      useExisting: forwardRef(() => MultiSelect),
    },
  ],
  host: {
    class: 'sn-multi-select',
    // The authored id belongs on the inner control, so the document never holds it twice.
    '[attr.id]': 'null',
    '[class]': 'snClassResolved()',
    '[class.sn-multi-select--has-chips]': 'hasChips()',
    '[attr.data-sn-open]': 'isOpen() ? "" : null',
    '[attr.data-sn-disabled]': 'isDisabled() ? "" : null',
    '[attr.data-sn-has-chips]': 'hasChips() ? "" : null',
  },
})
export class MultiSelect implements ControlValueAccessor, OnInit, OnDestroy, SnPartSource {
  protected readonly icons = inject(SnIconRegistry);

  readonly value = model<unknown[]>([]);
  readonly placeholder = input<string | undefined>(undefined);
  readonly disabled = input(false, { transform: booleanAttribute });
  readonly maxChips = input(3, { transform: numberAttribute });
  readonly ariaLabel = input<string | undefined>(undefined);
  /**
   * The control's `id`. Defaults to one generated by the enclosing
   * `sn-form-field`, whose `sn-label` points at it; set it to use your own and
   * the label follows.
   */
  readonly id = input<string>();
  /** Extra ids describing the control, merged with the field's hint and error ids. */
  readonly ariaDescribedby = input<string>(undefined, { alias: 'aria-describedby' });
  readonly snClass = input<SnClass>();
  readonly snStyle = input<SnStyle>();
  readonly snAttrs = input<SnAttrs>();
  readonly animated = input(true, { transform: booleanAttribute });
  /**
   * `animated` AND-ed with the app-wide motion setting. Read this, never
   * `animated()` directly, or SN_ANIMATIONS_DISABLED and prefers-reduced-motion
   * cannot skip the exit animation.
   */
  readonly _animated = snAnimated(this.animated);
  readonly animation = input<SnShowHideAnimation | undefined>(undefined);

  protected readonly options = contentChildren(ListOption);
  protected readonly panelTpl = viewChild<TemplateRef<unknown>>('panelTpl');
  protected readonly triggerBtn = viewChild<ElementRef<HTMLButtonElement>>('triggerBtn');

  private readonly injector = inject(Injector);
  private readonly intl = inject(SnSelectIntl);
  private readonly vcr = inject(ViewContainerRef);
  protected readonly fieldContext = inject(SN_FORM_FIELD, { optional: true });

  private readonly disabledFromForms = signal(false);
  readonly isDisabled = computed(() => this.disabled() || this.disabledFromForms());

  readonly panelId = snNextId('sn-multi-select-panel');
  private readonly _triggerId = snNextId('sn-multi-select-trigger');
  private readonly attrs = snControlAttrs({
    id: this.id,
    describedBy: this.ariaDescribedby,
    fallbackId: this._triggerId,
  });

  protected readonly triggerId = this.attrs.controlId;

  protected readonly effectivePlaceholder = computed(
    () => this.placeholder() ?? this.intl.placeholder,
  );

  private readonly optionValues = computed(() => this.options().map((option) => option.value()));
  private readonly selection = snSelectionModel<unknown>(() => ({
    multiple: true,
    unique: true,
    orderBy: this.optionValues,
    value: this.value,
  }));

  protected readonly selectedOptions = computed(() => {
    const vals = this.selection.selected();
    if (!Array.isArray(vals) || vals.length === 0) return [];
    return this.options().filter((o) => vals.includes(o.value()));
  });

  protected readonly hasChips = computed(() => this.selectedOptions().length > 0);

  protected readonly shownChips = computed(() => this.selectedOptions().slice(0, this.maxChips()));

  protected readonly hiddenCount = computed(() =>
    Math.max(0, this.selectedOptions().length - this.maxChips()),
  );

  protected readonly snClassResolved = computed(() => resolveSnClass(this.snClass(), 'root', true));

  protected readonly triggerClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'trigger', false),
  );

  protected readonly valueClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'value', false),
  );

  protected readonly arrowClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'arrow', false),
  );

  protected readonly panelClassExtra = computed(() =>
    resolveSnClass(this.snClass(), 'panel', false),
  );

  protected readonly chipClassExtra = computed(() => resolveSnClass(this.snClass(), 'chip', false));

  // The chip is a repeated child that owns its own parts, so the chip section is
  // forwarded into each Chip's inputs rather than applied with snPart from here.
  protected readonly chipStyleExtra = computed(() => resolveSnStyle(this.snStyle(), 'chip', false));
  protected readonly chipAttrsExtra = computed(() => resolveSnAttrs(this.snAttrs(), 'chip', false));

  readonly reservedAttrs = (section: string): readonly string[] =>
    MULTI_SELECT_RESERVED_ATTRS[section] ?? [];

  protected readonly ariaDescribedBy = this.attrs.describedBy;

  protected readonly isOpen = signal(false);
  protected readonly isClosing = signal(false);

  protected readonly panelAnimation = computed(() => {
    if (!this._animated()) return 'none';
    const custom = this.animation();
    return (this.isClosing() ? custom?.exit : custom?.enter) ?? null;
  });
  protected readonly activeOptionId = signal<string | null>(null);

  readonly context = {
    value: this.value as ReturnType<typeof signal<unknown>>,
    multiple: signal(true) as ReturnType<typeof signal<boolean>>,
    checkbox: signal(true) as ReturnType<typeof signal<boolean>>,
    isDisabled: this.isDisabled,
    // Through the selection model, which owns the selection.
    isSelected: (val: unknown): boolean => this.selection.isSelected(val),
    toggle: (val: unknown): void => {
      if (this.isDisabled()) return;
      this.selection.toggle(val);
      this.selection.set(
        this.selection.selected().filter((selected) => this.optionValues().includes(selected)),
      );
      const next = [...this.selection.selected()];
      this.onChangeFn(next);
      this.onTouchedFn();
      this.fieldContext?.setFilled(next.length > 0);
    },
    getTabIndex: (_option: unknown): number => -1,
    onTouched: (): void => this.onTouchedFn(),
  };

  private onChangeFn: (value: unknown[]) => void = () => {};
  private onTouchedFn: () => void = () => {};

  private keyManager: ActiveDescendantKeyManager<ListOption> | null = null;
  private subs = new Subscription();
  private readonly panel = snOverlayPanel(() =>
    snOverlaySelect({
      origin: this.triggerBtn()?.nativeElement,
      template: this.panelTpl(),
      viewContainerRef: this.vcr,
      panelClass: 'sn-select-overlay-panel',
      backdropClass: 'sn-select-backdrop',
      closeOnEscape: false,
      closeOnBackdrop: false,
      restoreFocus: false,
      animated: this._animated(),
      animation: this.animation(),
    }),
  );

  ngOnInit(): void {
    const currentVal = this.value();
    const filled = Array.isArray(currentVal) && currentVal.length > 0;
    this.fieldContext?.setFilled(filled);
  }

  ngOnDestroy(): void {
    this.keyManager?.destroy();
    this.subs.unsubscribe();
    this.panel.dispose();
  }

  protected onTriggerClick(): void {
    if (this.isDisabled()) return;
    if (this.isOpen()) {
      this.requestClose();
    } else {
      this.openPanel();
    }
  }

  protected onTriggerKeydown(event: KeyboardEvent): void {
    if (this.isDisabled()) return;
    const key = event.keyCode;

    if (this.isOpen()) {
      this.onOpenKeydown(event);
      return;
    }

    if (
      key === ENTER ||
      key === SPACE ||
      key === DOWN_ARROW ||
      key === UP_ARROW ||
      key === HOME ||
      key === END
    ) {
      event.preventDefault();
      this.openPanel();
      if (key === HOME) {
        setTimeout(() => {
          this.keyManager?.setFirstItemActive();
          this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
          this.scrollActiveIntoView();
        }, 0);
      } else if (key === END) {
        setTimeout(() => {
          this.keyManager?.setLastItemActive();
          this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
          this.scrollActiveIntoView();
        }, 0);
      }
    }
  }

  protected onChipContainerClick(event: MouseEvent): void {
    // Swallow only clicks on a chip; the empty chip row must still open the panel.
    if ((event.target as HTMLElement).closest('sn-chip')) {
      event.stopPropagation();
    }
  }

  protected toggleChip(val: unknown): void {
    this.context.toggle(val);
  }

  private openPanel(): void {
    if (this.isOpen() && !this.isClosing()) return;
    if (this.panel.isClosing()) this.panel.detach();
    if (!this.panel.open()) return;

    this.isOpen.set(true);
    this.isClosing.set(false);
    this.fieldContext?.registerFocus(true);
    this.bindOverlayEvents();

    setTimeout(() => {
      this.initKeyManager();
    }, 0);
  }

  private initKeyManager(): void {
    if (!this.panel.isOpen()) return;

    const itemsSignal = computed(() => this.options() as ListOption[]);

    this.keyManager = new ActiveDescendantKeyManager<ListOption>(itemsSignal, this.injector)
      .withVerticalOrientation()
      .withHomeAndEnd()
      .withTypeAhead()
      .skipPredicate((o: ListOption) => o.isDisabled());

    this.subs.add(
      this.keyManager.change.subscribe(() => {
        this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
      }),
    );

    this.keyManager.setFirstItemActive();
    this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
    this.scrollActiveIntoView();
  }

  private scrollActiveIntoView(): void {
    const active = this.keyManager?.activeItem;
    if (active && typeof active._el.nativeElement.scrollIntoView === 'function') {
      active._el.nativeElement.scrollIntoView({ block: 'nearest' });
    }
  }

  /**
   * Keys while the panel is open. The trigger's own handler and CDK's overlay
   * keyboard dispatcher both see a keydown on the trigger, so the dispatcher
   * path skips those to apply each key once.
   */
  private onOpenKeydown(event: KeyboardEvent): void {
    const key = event.keyCode;
    if (key === ESCAPE) {
      event.preventDefault();
      this.requestClose();
      return;
    }
    if (key === TAB) {
      this.detach();
      return;
    }
    if (key === ENTER || key === SPACE) {
      event.preventDefault();
      const active = this.keyManager?.activeItem;
      if (active && !active.isDisabled()) {
        this.context.toggle(active.value());
      }
      return;
    }
    if (key === DOWN_ARROW || key === UP_ARROW || key === HOME || key === END) {
      event.preventDefault();
      this.keyManager?.onKeydown(event);
      this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
      this.scrollActiveIntoView();
      return;
    }
    this.keyManager?.onKeydown(event);
    this.activeOptionId.set(this.keyManager?.activeItem?.id() ?? null);
  }

  private bindOverlayEvents(): void {
    this.subs.add(this.panel.backdropClick.subscribe(() => this.requestClose()));
    this.subs.add(
      this.panel.keydown.subscribe((event: KeyboardEvent) => {
        if (this.triggerBtn()?.nativeElement.contains(event.target as Node)) return;
        this.onOpenKeydown(event);
      }),
    );
    this.subs.add(this.panel.afterClosed.subscribe(() => this.finalizeDetach()));
  }

  protected requestClose(): void {
    if (!this.isOpen() || this.isClosing()) return;
    this.isClosing.set(true);
    this.panel.close();
  }

  private detach(): void {
    this.panel.detach();
  }

  private finalizeDetach(): void {
    // Clear the highlight: a fresh manager on each open has no memory of the last active option.
    this.keyManager?.setActiveItem(-1);
    this.keyManager?.destroy();
    this.keyManager = null;
    this.subs.unsubscribe();
    this.subs = new Subscription();
    this.isOpen.set(false);
    this.isClosing.set(false);
    this.activeOptionId.set(null);
    this.onTouchedFn();
    this.fieldContext?.registerFocus(false);
    this.restoreFocus();
  }

  private restoreFocus(): void {
    this.triggerBtn()?.nativeElement.focus();
  }

  writeValue(value: unknown): void {
    const arr = Array.isArray(value) ? value : [];
    this.value.set(arr);
    this.fieldContext?.setFilled(arr.length > 0);
  }

  registerOnChange(fn: (value: unknown[]) => void): void {
    this.onChangeFn = fn;
  }

  registerOnTouched(fn: () => void): void {
    this.onTouchedFn = fn;
  }

  setDisabledState(disabled: boolean): void {
    this.disabledFromForms.set(disabled);
  }
}
